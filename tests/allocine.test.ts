import { expect, it, vi } from "vitest";
import { openAllocine } from "../src/main/allocine";
import { allocineSearch, isAllocineSearch } from "../src/shared/allocine";
import { ipc } from "../src/shared/ipc";

it.each([
  ["Le Fabuleux Destin d’Amélie Poulain", 2001],
  ["千と千尋の神隠し", null],
  ["Alien", 1979],
  ["Alien", 2001],
  ["Été & nuit? #1 + São Paulo", null],
] as const)("encodes the film and optional year as one query for %s", (title, year) => {
  const value = allocineSearch({ title, year });
  expect(isAllocineSearch(value)).toBe(true);
  expect(new URL(value).searchParams.get("q")).toBe(year === null ? title : `${title} ${year}`);
});

it("rejects untrusted URLs and extra payload fields", () => {
  for (const url of [
    "http://www.allocine.fr/rechercher/movie/?q=a",
    "javascript:alert(1)",
    "file:///rechercher/movie/?q=a",
    "https://www.allocine.fr.evil.test/rechercher/movie/?q=a",
    "https://www.allocine.fr@evil.test/rechercher/movie/?q=a",
    "https://evil.test@www.allocine.fr/rechercher/movie/?q=a",
    "https://www.allocine.fr:8443/rechercher/movie/?q=a",
    "https://subdomain.allocine.fr/rechercher/movie/?q=a",
    "https://www.allocine.fr/rechercher/movie/?q=a&next=https://evil.test",
    "https://www.allocine.fr/rechercher/movie/?q=a&q=b",
    "https://www.allocine.fr/redirect/?q=a",
  ]) {
    expect(isAllocineSearch(url)).toBe(false);
    expect(ipc.openAllocine.request.safeParse([url]).success).toBe(false);
    expect(ipc.openAllocine.request.safeParse([{ title: "Film", year: null, url }]).success).toBe(false);
  }
});

it("opens only the search generated by main", async () => {
  const external = vi.fn(async () => undefined);
  const [film] = ipc.openAllocine.request.parse([{ title: "  Film: #1 & film  ", year: 0 }]);
  await openAllocine(film, external);
  expect(external).toHaveBeenCalledExactlyOnceWith("https://www.allocine.fr/rechercher/movie/?q=Film%3A+%231+%26+film");
});
